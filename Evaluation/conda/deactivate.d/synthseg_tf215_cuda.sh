#!/usr/bin/env bash

if [[ "${SYNTHSEG_TF215_HAD_LD_LIBRARY_PATH:-0}" == 1 ]]; then
    export LD_LIBRARY_PATH="${SYNTHSEG_TF215_OLD_LD_LIBRARY_PATH}"
else
    unset LD_LIBRARY_PATH
fi

if [[ "${SYNTHSEG_TF215_HAD_TF_FORCE_GPU_ALLOW_GROWTH:-0}" == 1 ]]; then
    export TF_FORCE_GPU_ALLOW_GROWTH="${SYNTHSEG_TF215_OLD_TF_FORCE_GPU_ALLOW_GROWTH}"
else
    unset TF_FORCE_GPU_ALLOW_GROWTH
fi

unset SYNTHSEG_TF215_OLD_LD_LIBRARY_PATH
unset SYNTHSEG_TF215_HAD_LD_LIBRARY_PATH
unset SYNTHSEG_TF215_OLD_TF_FORCE_GPU_ALLOW_GROWTH
unset SYNTHSEG_TF215_HAD_TF_FORCE_GPU_ALLOW_GROWTH
